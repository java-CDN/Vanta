#!/usr/bin/env python3
"""Generate .github/workflows/engine-s3.yml (chained compile stages).

Same design as ungoogled-chromium-windows .github/workflows/reusable-build.yml
(generated there by .github/scripts/gen.py): N identical jobs, each `needs`
the previous one; a job runs ninja until its time is up, archives build/src
(sources + out dir, 7z zip with NTFS timestamps) as an artifact and the next
job restores it and continues. Run this after changing the template:

  python3 engine/scripts/gen_s3_workflow.py [--stages 10]
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

HEADER = r'''# GENERATED by engine/scripts/gen_s3_workflow.py; edit the generator, not this file.
name: engine-s3

# S3 (Master Plan v3, 5.4): compile the patched engine on free GitHub runners
# and package vanta-engine-win64.zip, then the S5-lite smoke on the same runner.
# Chained stages as ungoogled-chromium-windows does it: every stage runs ninja
# until its deadline, archives build/src as artifact "build-state" (retention
# 1 day, overwritten by each stage) and the next stage continues. Stage 1 also
# prepares the tree exactly like S2 (+ bindgen). The stage that finishes ninja
# packages, uploads "vanta-engine-win64" (7 days) and runs the smoke test.
# Dispatch only (a full chain is 10-20+ runner hours). See docs/engine-build.md.

on:
  workflow_dispatch:
    inputs:
      jobs:
        description: ninja -j (4 vCPU / 16 GB runner; 2 as ucw, avoids ThinLTO OOM)
        default: '2'
      ninja_deadline_minutes:
        description: minutes after a stage starts at which ninja is stopped (job limit 360)
        default: '270'
      resume_run_id:
        description: continue from the build-state artifact of this run id (within 1 day); Vanta patches are re-synced
        default: ''

permissions:
  contents: read
  actions: write   # overwrite/delete build-state, download it from another run

concurrency:
  group: engine-s3
  cancel-in-progress: false

jobs:
'''

STAGE = r'''  stage-{k}:
    name: S3 stage {k}{title}
{needs}    runs-on: windows-2022
    timeout-minutes: 355
    outputs:
      finished: ${{{{ steps.ninja.outputs.finished }}}}
      edges_done: ${{{{ steps.ninja.outputs.edges_done }}}}
      edges_total: ${{{{ steps.ninja.outputs.edges_total }}}}
      work: ${{{{ steps.env.outputs.work }}}}
    steps:
      - name: Stage clock, work dir, runner
        id: env
        run: |
          $t0 = [DateTimeOffset]::UtcNow.ToUnixTimeSeconds()
          "STAGE_DEADLINE=$($t0 + 60 * [int]'${{{{ inputs.ninja_deadline_minutes }}}}')" >> $env:GITHUB_ENV
          Get-PSDrive -PSProvider FileSystem | Format-Table Name, Used, Free
          {work_rule}
          "WORK=$work" >> $env:GITHUB_ENV
          "work=$work" >> $env:GITHUB_OUTPUT
          New-Item -ItemType Directory -Force -Path $work | Out-Null
          Write-Host "work dir: $work; image: $env:ImageOS $env:ImageVersion"
          & "${{env:ProgramFiles(x86)}}\Microsoft Visual Studio\Installer\vswhere.exe" -latest -property displayName
          # Same as most Chromium-on-Actions builds: Defender scanning every .obj halves throughput.
          Set-MpPreference -DisableRealtimeMonitoring $true -ErrorAction SilentlyContinue
          Add-MpPreference -ExclusionPath $work -ErrorAction SilentlyContinue

      - uses: actions/checkout@v4

      # Pinned patch version: gn records the python path in build.ninja, so it
      # must be the same in every stage of the chain.
      - uses: actions/setup-python@v5
        with:
          python-version: '3.12.10'

      # Same as ungoogled-chromium-windows .github/actions/prepare at the pinned tag.
      - name: Install Windows SDK 10.0.28000.0
        run: |
          if (Test-Path 'C:\Program Files (x86)\Windows Kits\10\Include\10.0.28000.0') {{
            Write-Host 'SDK 10.0.28000.0 already installed.'
            exit 0
          }}
          $installer = "$env:TEMP\winsdksetup.exe"
          Invoke-WebRequest -Uri 'https://download.microsoft.com/download/38ab8f6d-3676-4860-ae84-3361308b9d7f/KIT_BUNDLE_WINDOWSSDK_MEDIACREATION/winsdksetup.exe' -OutFile $installer
          $features = '/features OptionId.DesktopCPPx64 OptionId.DesktopCPPx86 OptionId.DesktopCPPArm64 OptionId.WindowsDesktopDebuggers OptionId.UWPCPP OptionId.SigningTools /q /norestart /ceip off'
          $proc = Start-Process -FilePath $installer -ArgumentList $features -PassThru -Wait
          if ($proc.ExitCode -ne 0) {{ throw "winsdksetup.exe failed with code $($proc.ExitCode)" }}
          if (-not (Test-Path 'C:\Program Files (x86)\Windows Kits\10\Include\10.0.28000.0')) {{
            throw 'SDK 10.0.28000.0 not found after install.'
          }}

      - name: Python deps (ucw stage action + smoke signer)
        run: python -m pip install httplib2==0.22.0 clang==21.1.7 cryptography

      - name: Fetch + verify upstream pins
        run: python engine/scripts/fetch_upstream.py "$env:WORK\ucw"
{prepare}
      - name: ninja chrome (until the stage deadline)
        id: ninja
        run: python engine/scripts/ci_ninja.py --src "$env:WORK\build\src" --deadline $env:STAGE_DEADLINE --jobs ${{{{ inputs.jobs }}}} --stage {k}{canary}

      - name: Archive build state for the next stage
        if: steps.ninja.outputs.finished == 'false'
        run: |
          $ErrorActionPreference = 'Stop'
          Set-Content -NoNewline "$env:WORK\build\src\.vanta_state\work.txt" $env:WORK
          Get-PSDrive -PSProvider FileSystem | Format-Table Name, Used, Free
          Start-Sleep 5
          $sw = [Diagnostics.Stopwatch]::StartNew()
          New-Item -ItemType Directory -Force -Path "$env:WORK\state-out" | Out-Null
          # As ucw: zip of build/src with NTFS timestamps (ninja needs them), level 3; 4 GB volumes.
          7z a -tzip "$env:WORK\state-out\build-state.zip" "$env:WORK\build\src" -mx=3 -mtc=on -v4g -bso0 -bsp0
          if ($LASTEXITCODE -ne 0) {{ throw "7z failed ($LASTEXITCODE)" }}
          Get-ChildItem "$env:WORK\state-out" | Format-Table Name, Length
          Write-Host "archived in $([int]$sw.Elapsed.TotalMinutes) min"

      - name: Upload build state
        if: steps.ninja.outputs.finished == 'false'
        uses: actions/upload-artifact@v4
        with:
          name: build-state
          path: ${{{{ env.WORK }}}}\state-out\
          retention-days: 1
          compression-level: 0
          overwrite: true
          if-no-files-found: error

      - name: Stop the chain on compile errors
        if: steps.ninja.outputs.failures != '' && steps.ninja.outputs.failures != '0'
        run: |
          Write-Host "::error::${{{{ steps.ninja.outputs.failures }}}} ninja edge(s) failed in stage {k}; build state was archived. Fix the patch, then dispatch with resume_run_id=${{{{ github.run_id }}}}."
          exit 1

      - name: Package vanta-engine-win64.zip
        id: pkg
        if: steps.ninja.outputs.finished == 'true'
        run: python engine/scripts/package_engine.py --ucw "$env:WORK\ucw" --src "$env:WORK\build\src" --dest "$env:WORK\dist"

      - name: Upload vanta-engine-win64
        if: steps.ninja.outputs.finished == 'true'
        uses: actions/upload-artifact@v4
        with:
          name: vanta-engine-win64
          path: ${{{{ env.WORK }}}}\dist\
          retention-days: 7
          compression-level: 0
          if-no-files-found: error

      - name: S5-lite smoke (no config / 86 / 87 / valid signed config)
        if: steps.ninja.outputs.finished == 'true'
        run: |
          $ErrorActionPreference = 'Stop'
          Expand-Archive "$env:WORK\dist\vanta-engine-win64.zip" "$env:WORK\smoke-bin" -Force
          python engine/scripts/smoke_s5lite.py --exe "$env:WORK\smoke-bin\vanta-engine-win64\vanta-chromium.exe" --work "$env:WORK\smoke"
          if ($LASTEXITCODE -ne 0) {{ throw "smoke failed" }}

      - name: Upload smoke logs
        if: always() && steps.ninja.outputs.finished == 'true'
        uses: actions/upload-artifact@v4
        with:
          name: s5-lite-logs
          path: ${{{{ env.WORK }}}}\smoke\*.log
          retention-days: 7
          if-no-files-found: ignore

      - name: Delete the intermediate build-state artifact
        if: always() && steps.ninja.outputs.finished == 'true'
        env:
          GH_TOKEN: ${{{{ github.token }}}}
        run: |
          $ids = gh api "repos/${{{{ github.repository }}}}/actions/runs/${{{{ github.run_id }}}}/artifacts" --jq '.artifacts[] | select(.name == "build-state") | .id'
          foreach ($id in $ids) {{ gh api -X DELETE "repos/${{{{ github.repository }}}}/actions/artifacts/$id" }}

'''

PREPARE_FRESH = r'''
      - name: Prepare tree (pinned tarball SHA-256, patches, domsub, rust, args, gn gen + check, bindgen)
        if: inputs.resume_run_id == ''
        run: python engine/scripts/prepare.py --ucw "$env:WORK\ucw" --build "$env:WORK\build" --steps source,windeps,prune,patch,domsub,rust,args,gngen,bindgen --delete-archives --no-progress
'''

RESTORE = r'''
      - name: Download build state ({what})
        {cond}uses: actions/download-artifact@v4
        with:
          name: build-state
          path: ${{{{ env.WORK }}}}\state
{extra}
      - name: Unpack build state, re-sync Vanta patches, gn gen
        {cond}run: |
          $ErrorActionPreference = 'Stop'
          $sw = [Diagnostics.Stopwatch]::StartNew()
          7z x "$env:WORK\state\build-state.zip.001" "-o$env:WORK\build" -y -bso0 -bsp0
          if ($LASTEXITCODE -ne 0) {{ throw "7z failed ($LASTEXITCODE)" }}
          Remove-Item -Recurse -Force "$env:WORK\state"
          Write-Host "restored in $([int]$sw.Elapsed.TotalMinutes) min"
          $was = Get-Content "$env:WORK\build\src\.vanta_state\work.txt"
          if ($was -ne $env:WORK) {{ throw "build state was made in $was, this runner uses $env:WORK" }}
          Get-PSDrive -PSProvider FileSystem | Format-Table Name, Used, Free
          python engine/scripts/prepare.py --ucw "$env:WORK\ucw" --build "$env:WORK\build" --steps resync,args,gngen,bindgen --no-gn-check
          if ($LASTEXITCODE -ne 0) {{ throw "prepare (resync) failed" }}
'''

FOOTER = r'''  complete:
    name: S3 result
    needs: [{all}]
    if: always()
    runs-on: ubuntu-latest
    steps:
      - name: Ensure the build finished
        run: |
          if [ "${{{{ contains(needs.*.outputs.finished, 'true') }}}}" != "true" ]; then
            echo "Build did not finish within {n} stages (or a stage failed)."
            exit 1
          fi
          echo "vanta-engine-win64 built and smoke-tested."
'''


def generate(n):
    out = [HEADER]
    for k in range(1, n + 1):
        if k == 1:
            needs = ''
            work_rule = ("$d = Get-PSDrive D -ErrorAction SilentlyContinue; "
                         "if ($d -and $d.Free -ge 150GB) { $work = 'D:\\vanta' } "
                         "else { $work = 'C:\\vanta' }")
            prepare = PREPARE_FRESH + RESTORE.format(
                what='resume_run_id', cond="if: inputs.resume_run_id != ''\n        ",
                extra=('          run-id: ${{ inputs.resume_run_id }}\n'
                       '          github-token: ${{ github.token }}\n'))
            title = ' (prepare + ninja)'
            canary = ' --canary'
        else:
            needs = (f"    needs: stage-{k - 1}\n"
                     f"    if: needs.stage-{k - 1}.outputs.finished == 'false'\n")
            work_rule = f"$work = '${{{{ needs.stage-{k - 1}.outputs.work }}}}'"
            prepare = RESTORE.format(what=f'stage {k - 1}', cond='', extra='')
            title = ' (ninja)'
            canary = ''
        out.append(STAGE.format(k=k, title=title, needs=needs, work_rule=work_rule,
                                prepare=prepare, canary=canary))
    out.append(FOOTER.format(all=', '.join(f'stage-{k}' for k in range(1, n + 1)), n=n))
    return ''.join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--stages', type=int, default=10)
    a = ap.parse_args()
    dst = ROOT / '.github' / 'workflows' / 'engine-s3.yml'
    dst.write_text(generate(a.stages), encoding='utf-8')
    print(f'wrote {dst} ({a.stages} stages)')


if __name__ == '__main__':
    main()
